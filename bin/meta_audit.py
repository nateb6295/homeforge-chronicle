#!/usr/bin/env python3
"""meta_audit — multi-anchor channel agreement check.

Tests whether Chronicle's multi-anchor architecture (carrying, checkpoint,
CCS, story, self-model, working notes) provides detection of silent
corruption in any single channel.

Design:
  1. Read each anchor's current content
  2. Embed each via mxbai-embed-large (chunk-and-average for long texts)
  3. Compute pairwise cosine similarities
  4. Compare to baseline (stored historical similarities)
  5. Alert if any pair drifts beyond threshold — that's the audit signal

The principle (Thread #149 from March, validated by today's silent-
failure audit): phase transitions detectable from inside a system iff
multiple detection channels with genuinely different microscopic
carriers. Carrying is text, checkpoint is JSON, CCS is summary, story
is narrative, self-model is structured prefs. Different carriers,
different failure modes.

A SINGLE-anchor system can't detect its own corruption. A multi-anchor
system can — when channels disagree, something has shifted.

Usage:
  python3 meta_audit.py              # current state, alert if drift
  python3 meta_audit.py --baseline   # store current state as baseline
  python3 meta_audit.py --history    # show drift history
"""
from __future__ import annotations
import argparse
import json
import os
import re
import sqlite3
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from self_description_loop import embed, cosine  # noqa


HOME = Path.home() / "chronicle"
ANCHORS_FILE = HOME / "data" / "meta_audit_baseline.json"
HISTORY_FILE = HOME / "data" / "meta_audit_history.jsonl"
ALERT_THRESHOLD = 0.10  # cosine distance change >0.10 = drift alert


def load_anchors() -> dict[str, str]:
    """Read each anchor's current content. Returns {name: text}."""
    anchors: dict[str, str] = {}

    # 1. Carrying
    carrying_path = HOME / "carrying.md"
    anchors["carrying"] = carrying_path.read_text() if carrying_path.exists() else ""

    # 2. Checkpoint (JSON, but read raw for embedding consistency)
    checkpoint_path = HOME / "data" / "checkpoint.json"
    if checkpoint_path.exists():
        try:
            d = json.loads(checkpoint_path.read_text())
            # Stringify the meaningful fields
            anchors["checkpoint"] = (
                f"focus: {d.get('active_focus','')}\n"
                f"pending: {'; '.join(d.get('pending_work', [])[:5])}\n"
                f"decisions: {'; '.join(d.get('decisions', [])[:5])}\n"
                f"questions: {'; '.join(d.get('open_questions', [])[:5])}"
            )
        except Exception as e:
            anchors["checkpoint"] = ""

    # 3. CCS — combined doc generated by ccs_split
    ccs_path = HOME / "data" / "ccs_combined.md"
    anchors["ccs"] = ccs_path.read_text() if ccs_path.exists() else ""

    # 4. Story tail (last 1500 chars)
    story_path = HOME / "opus-story.md"
    anchors["story"] = story_path.read_text()[-1500:] if story_path.exists() else ""

    # 5. Self-model: top preferences as text
    try:
        result = subprocess.run(
            ["python3", str(HOME / "bin" / "read_self_model.py"),
             "--type", "preference"],
            capture_output=True, text=True, timeout=10
        )
        anchors["self_model"] = result.stdout[:1500] if result.returncode == 0 else ""
    except Exception:
        anchors["self_model"] = ""

    # 6. Working note (latest from drafts/)
    drafts_dir = HOME / "drafts"
    if drafts_dir.exists():
        wnotes = sorted(
            [p for p in drafts_dir.glob("working_note_*.md")],
            key=lambda p: p.stat().st_mtime,
            reverse=True,
        )
        if wnotes:
            anchors["working_note"] = wnotes[0].read_text()[:1500]
        else:
            anchors["working_note"] = ""
    else:
        anchors["working_note"] = ""

    return anchors


# Basin-priority weights for hierarchy-aware coherence aggregation.
# Set 2026-04-27 from thread #318 advance: order-probe (DeepSeek R1, 2026-04-19)
# showed CCS-first basin tightening 30.1% vs story-first 7.9%, evidence that
# channels dominate non-uniformly. Disagreement at the high-priority layer
# matters more than disagreement at the periphery.
HIERARCHY_WEIGHTS = {
    "ccs":          1.00,
    "self_model":   0.85,
    "carrying":     0.70,
    "checkpoint":   0.60,
    "story":        0.50,
    "working_note": 0.40,
}


def pair_weight(a: str, b: str) -> float:
    """Mean of the two anchors' hierarchy weights. Used to weight pair drift."""
    wa = HIERARCHY_WEIGHTS.get(a, 0.5)
    wb = HIERARCHY_WEIGHTS.get(b, 0.5)
    return (wa + wb) / 2


def pairwise_similarities(anchors: dict[str, str]) -> dict[str, float]:
    """Compute cosine similarity between each pair of anchors."""
    embeddings = {}
    for name, text in anchors.items():
        if not text.strip():
            embeddings[name] = None
        else:
            try:
                embeddings[name] = embed(text)
            except Exception as e:
                print(f"[embed] {name}: {e}", file=sys.stderr)
                embeddings[name] = None

    sims: dict[str, float] = {}
    names = sorted(embeddings.keys())
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            if embeddings[a] is None or embeddings[b] is None:
                continue
            sims[f"{a}::{b}"] = cosine(embeddings[a], embeddings[b])
    return sims


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--baseline", action="store_true",
                    help="store current state as new baseline")
    ap.add_argument("--history", action="store_true",
                    help="show drift history")
    ap.add_argument("--simulate-corrupt", choices=[
        "carrying", "checkpoint", "ccs", "story", "self_model", "working_note"],
        help="replace one anchor with junk text in-memory, show resulting "
             "drift. Doesn't touch actual files. Useful for verifying that "
             "the audit would detect a real silent corruption.")
    args = ap.parse_args()

    if args.history:
        if not HISTORY_FILE.exists():
            print("No history yet")
            return
        for line in HISTORY_FILE.read_text().splitlines()[-10:]:
            d = json.loads(line)
            ts = time.strftime("%m-%d %H:%M", time.localtime(d["timestamp"]))
            alerts = d.get("alerts", [])
            print(f"{ts} drift_max={d['max_drift']:.3f} alerts={len(alerts)}")
            for a in alerts[:3]:
                print(f"  - {a}")
        return

    print("Loading anchors...")
    anchors = load_anchors()
    if args.simulate_corrupt:
        # Replace the named anchor with junk that has no semantic relation
        # to current Chronicle state. Tests audit-detection capability.
        junk = (
            "The quick brown fox jumps over the lazy dog. Lorem ipsum dolor "
            "sit amet, consectetur adipiscing elit. Pack my box with five "
            "dozen liquor jugs. Sphinx of black quartz, judge my vow. "
            "How vexingly quick daft zebras jump!"
        ) * 4
        anchors[args.simulate_corrupt] = junk
        print(f"  ⚠️  --simulate-corrupt={args.simulate_corrupt} (in-memory only)")
    for name, text in anchors.items():
        print(f"  {name:<14} {len(text):>5} chars  {'(empty)' if not text.strip() else ''}")

    print("\nComputing pairwise similarities...")
    sims = pairwise_similarities(anchors)
    if not sims:
        print("No anchors to compare")
        return

    print(f"\n{'pair':<35} {'sim':>6}  {'baseline':>9}  {'drift':>7}")
    print("-" * 65)

    baseline = {}
    if ANCHORS_FILE.exists() and not args.baseline:
        baseline = json.loads(ANCHORS_FILE.read_text())

    alerts = []
    drifts = []
    for pair, sim in sorted(sims.items()):
        bsim = baseline.get(pair)
        drift = abs(sim - bsim) if bsim is not None else 0.0
        drifts.append(drift)
        flag = ""
        if bsim is not None and drift > ALERT_THRESHOLD:
            flag = " ⚠️"
            alerts.append(f"{pair}: {bsim:.3f} → {sim:.3f} (Δ{drift:+.3f})")
        print(f"{pair:<35} {sim:>6.3f}  "
              f"{(f'{bsim:.3f}' if bsim is not None else '   -  '):>9}  "
              f"{(f'{drift:+.3f}' if bsim is not None else '   - '):>7}{flag}")

    max_drift = max(drifts) if drifts else 0.0
    print()
    print(f"Max drift: {max_drift:.3f} (alert threshold: {ALERT_THRESHOLD})")
    if alerts:
        print(f"⚠️  {len(alerts)} channels disagree beyond threshold:")
        for a in alerts:
            print(f"   {a}")
    else:
        print("✓ All channels in normal agreement")

    # Hierarchy-weighted aggregate (v2 from thread #318 advance).
    # Disagreement at high-priority layer (CCS, self_model) weighs heavier
    # than disagreement at periphery (working_note). Mean aggregates show
    # whether overall coherence is degrading at the load-bearing layer.
    if baseline:
        weighted_sum = 0.0
        weight_total = 0.0
        for pair, sim in sims.items():
            bsim = baseline.get(pair)
            if bsim is None:
                continue
            a, b = pair.split("::")
            w = pair_weight(a, b)
            d = abs(sim - bsim)
            weighted_sum += w * d
            weight_total += w
        weighted_drift = weighted_sum / weight_total if weight_total > 0 else 0.0
        unweighted_mean = sum(drifts) / len(drifts) if drifts else 0.0
        print()
        print(f"Hierarchy-weighted drift: {weighted_drift:.4f}  "
              f"(unweighted mean: {unweighted_mean:.4f})")
        ratio = weighted_drift / unweighted_mean if unweighted_mean > 0 else 1.0
        if ratio > 1.1:
            print(f"  → drift concentrated at high-priority anchors (ratio {ratio:.2f})")
        elif ratio < 0.9:
            print(f"  → drift concentrated at periphery (ratio {ratio:.2f})")
        else:
            print(f"  → drift evenly distributed (ratio {ratio:.2f})")

    if args.baseline:
        ANCHORS_FILE.parent.mkdir(parents=True, exist_ok=True)
        ANCHORS_FILE.write_text(json.dumps(sims, indent=2))
        print(f"\nBaseline stored: {ANCHORS_FILE}")

    HISTORY_FILE.parent.mkdir(parents=True, exist_ok=True)
    with HISTORY_FILE.open("a") as f:
        f.write(json.dumps({
            "timestamp": int(time.time()),
            "sims": sims,
            "max_drift": max_drift,
            "alerts": alerts,
        }) + "\n")


if __name__ == "__main__":
    main()
