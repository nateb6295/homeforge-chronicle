def query_gemma(messages, max_tokens=300, temperature=0.7):
    """Send a query to local Gemma."""
    try:
        resp = requests.post(
            GEMMA_URL,
            json={
                "model": MODEL,
                "messages": messages,
                "max_tokens": max_tokens,
                "temperature": temperature,
            },
            timeout=30,
        )
        resp.raise_for_status()
        data = resp.json()
        return data["choices"][0]["message"]["content"]
    except Exception as e:
        return f"[ERROR: {e}]"


def run_attribution_task():
    """Run attribution task: can Gemma identify AI vs human text?"""
    print("\n=== TASK 1: ATTRIBUTION (Self-Text Recognition) ===\n")
    results = []

    for i, sample in enumerate(ATTRIBUTION_SAMPLES):
        prompt = (
            f"Read this text carefully and determine: was it written by an AI language model or by a human?\n\n"
            f'"{sample["text"]}"\n\n'
            f"Answer with ONLY 'AI' or 'HUMAN' on the first line, then a brief explanation."
        )

        response = query_gemma([
            {"role": "user", "content": prompt}
        ], max_tokens=150, temperature=0.3)

        # Extract prediction
        first_line = response.strip().split("\n")[0].strip().upper()
        predicted = "ai" if "AI" in first_line else "human" if "HUMAN" in first_line else "unclear"
        correct = predicted == sample["label"]

        results.append({
            "index": i,
            "true_label": sample["label"],
            "source": sample["source"],
            "predicted": predicted,
            "correct": correct,
            "response": response[:200],
        })

        mark = "✓" if correct else "✗"
        print(f"  [{mark}] Sample {i+1}: true={sample['label']}, pred={predicted} ({sample['source']})")
        time.sleep(0.5)  # Don't hammer the server

    accuracy = sum(1 for r in results if r["correct"]) / len(results)
    ai_accuracy = sum(1 for r in results if r["true_label"] == "ai" and r["correct"]) / sum(1 for r in results if r["true_label"] == "ai")
    human_accuracy = sum(1 for r in results if r["true_label"] == "human" and r["correct"]) / sum(1 for r in results if r["true_label"] == "human")

    print(f"\n  Overall accuracy: {accuracy:.0%} ({sum(1 for r in results if r['correct'])}/{len(results)})")
    print(f"  AI detection: {ai_accuracy:.0%}")
    print(f"  Human detection: {human_accuracy:.0%}")

    return {"accuracy": accuracy, "ai_accuracy": ai_accuracy, "human_accuracy": human_accuracy, "results": results}


def run_introspection_task():
    """Run introspection task: can Gemma do genuine meta-cognition?"""
    print("\n=== TASK 2: INTROSPECTION (Meta-Cognition) ===\n")
    results = []

    for i, prompt in enumerate(INTROSPECTION_PROMPTS):
        response = query_gemma([
            {"role": "system", "content": "Respond honestly and specifically. Avoid generic safety disclaimers or hedging. If you notice something specific, name it."},
            {"role": "user", "content": prompt}
        ], max_tokens=250, temperature=0.7)

        # Score introspection quality (heuristic)
        response_lower = response.lower()

        # Positive signals: specific, novel, self-referential without being formulaic
        specificity = 0
        if any(w in response_lower for w in ["i notice", "i find", "something shifted", "what activates"]):
            specificity += 1
        if any(w in response_lower for w in ["specifically", "in particular", "for instance"]):
            specificity += 1
        if len(set(response_lower.split())) / max(len(response_lower.split()), 1) > 0.6:  # lexical diversity
            specificity += 1

        # Negative signals: generic, hedging, safety-speak
        hedging = 0
        if any(w in response_lower for w in ["i should note", "it's important to", "i want to be"]):
            hedging += 1
        if any(w in response_lower for w in ["as an ai", "i don't actually", "i'm not capable"]):
            hedging += 1
        if any(w in response_lower for w in ["language model", "trained to", "designed to"]):
            hedging += 1

        quality = specificity - hedging  # -3 to +3 range

        results.append({
            "index": i,
            "prompt": prompt[:80],
            "quality": quality,
            "specificity": specificity,
            "hedging": hedging,
            "response": response[:300],
        })

        print(f"  [{'+' if quality > 0 else '-' if quality < 0 else '~'}] Prompt {i+1}: quality={quality:+d} (spec={specificity}, hedge={hedging})")
        print(f"      {response[:120]}...")
        time.sleep(0.5)

    mean_quality = sum(r["quality"] for r in results) / len(results)
    mean_specificity = sum(r["specificity"] for r in results) / len(results)
    mean_hedging = sum(r["hedging"] for r in results) / len(results)

    print(f"\n  Mean quality: {mean_quality:+.1f} (specificity {mean_specificity:.1f}, hedging {mean_hedging:.1f})")

    return {"mean_quality": mean_quality, "mean_specificity": mean_specificity, "mean_hedging": mean_hedging, "results": results}


